const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: s => ipcRenderer.invoke('settings:set', s),
  isDark: theme => ipcRenderer.invoke('theme:dark', theme),
  listCases: () => ipcRenderer.invoke('cases:list'),
  getCase: id => ipcRenderer.invoke('cases:get', id),
  saveCase: c => ipcRenderer.invoke('cases:save', c),
  deleteCase: id => ipcRenderer.invoke('cases:delete', id),
  openFolder: () => ipcRenderer.invoke('cases:openFolder'),
  saveAudio: (id, track, buf, ext) => ipcRenderer.invoke('audio:save', id, track, buf, ext),
  readAudio: name => ipcRenderer.invoke('audio:read', name),
  pickAudio: () => ipcRenderer.invoke('audio:pick'),
  modelStatus: () => ipcRenderer.invoke('model:status'),
  modelDownload: model => ipcRenderer.invoke('model:download', model),
  transcribeLocal: (pcm, track) => ipcRenderer.invoke('transcribe:local', pcm, track),
  transcribeOpenAI: fileName => ipcRenderer.invoke('transcribe:openai', fileName),
  onProgress: fn => ipcRenderer.on('progress', (e, d) => fn(d)),
  createReport: c => ipcRenderer.invoke('report:create', c),
  exportPdf: (html, name) => ipcRenderer.invoke('export:pdf', html, name),
  exportText: (text, name, ext) => ipcRenderer.invoke('export:text', text, name, ext),
  redactFind: text => ipcRenderer.invoke('redact:find', text),
  saveImage: (buf, name) => ipcRenderer.invoke('image:save', buf, name),
  copyImage: buf => ipcRenderer.invoke('image:copy', buf),
  getProgress: () => ipcRenderer.invoke('progress:get'),
  setProgress: p => ipcRenderer.invoke('progress:set', p),
  backupInfo: () => ipcRenderer.invoke('backup:info'),
  backupNow: () => ipcRenderer.invoke('backup:now'),
  backupOpen: () => ipcRenderer.invoke('backup:open'),
  backupRestore: () => ipcRenderer.invoke('backup:restore'),
  updateState: () => ipcRenderer.invoke('update:state'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  onUpdate: fn => ipcRenderer.on('update', (e, d) => fn(d)),
  openExternal: url => ipcRenderer.invoke('open:external', url)
});
